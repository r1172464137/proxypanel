param([ValidateSet('windows-amd64','linux-amd64','linux-arm64')][string[]]$Targets = @('windows-amd64','linux-amd64','linux-arm64'))
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Use-DevEnvironment.ps1')
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$oldOS=$env:GOOS; $oldArch=$env:GOARCH; $oldCGO=$env:CGO_ENABLED
Push-Location $root
try {
    Push-Location web
    try { npm run build; if ($LASTEXITCODE -ne 0) { throw 'Frontend build failed' } } finally { Pop-Location }
    foreach ($target in $Targets) {
        $parts=$target.Split('-'); $env:GOOS=$parts[0]; $env:GOARCH=$parts[1]; $env:CGO_ENABLED='0'
        $out=Join-Path $root "build\$target"
        if (Test-Path -LiteralPath $out) {
            if (-not (Test-Path -LiteralPath (Join-Path $out '.proxypanel-build'))) { throw "Refusing to replace unmarked output: $out" }
            if ((Get-Item -LiteralPath $out).Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Refusing linked build output' }
            Remove-Item -LiteralPath $out -Recurse -Force
        }
        New-Item -ItemType Directory -Path $out -Force | Out-Null
        [IO.File]::WriteAllText((Join-Path $out '.proxypanel-build'), 'Generated by Build-Release.ps1')
        $suffix=if ($env:GOOS -eq 'windows') { '.exe' } else { '' }
        foreach ($component in @('panel','agent')) {
            go build -trimpath -o (Join-Path $out ($component+$suffix)) "./cmd/$component"
            if ($LASTEXITCODE -ne 0) { throw "Build failed: $target/$component" }
        }
        foreach ($item in @('migrations','configs','deploy')) { Copy-Item -LiteralPath (Join-Path $root $item) -Destination $out -Recurse -Force }
        New-Item -ItemType Directory -Path (Join-Path $out 'web') -Force | Out-Null
        Copy-Item -LiteralPath (Join-Path $root 'web\dist') -Destination (Join-Path $out 'web') -Recurse -Force
        $hashes=Get-ChildItem -LiteralPath $out -Recurse -File | Where-Object Name -ne 'SHA256SUMS' | Sort-Object FullName | ForEach-Object {
            $relative=[IO.Path]::GetRelativePath($out,$_.FullName).Replace('\','/')
            "$((Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant())  $relative"
        }
        [IO.File]::WriteAllText((Join-Path $out 'SHA256SUMS'), (($hashes -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
        Write-Host "Built $target (cross-build is not platform runtime verification)."
    }
} finally {
    $env:GOOS=$oldOS; $env:GOARCH=$oldArch; $env:CGO_ENABLED=$oldCGO
    Pop-Location
}
